import sqlite3

import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression

from src.config import DATABASE_PATH, DOCS_DIR, EXPORT_DIR, SQL_DIR


CAPS = (0.10, 0.15, 0.20)


def _price_sensitivity(items: pd.DataFrame) -> pd.DataFrame:
    items["order_date"] = pd.to_datetime(items["order_date"])
    items["week"] = items["order_date"].dt.to_period("W-SUN").dt.start_time
    weekly = (
        items.groupby(["category_name", "week"], as_index=False)
        .agg(
            orders=("order_id", "nunique"),
            units=("quantity", "sum"),
            net_sales=("net_sales", "sum"),
        )
    )
    weekly["average_net_unit_price"] = weekly["net_sales"] / weekly["units"]

    rows = []
    for category, group in weekly.groupby("category_name"):
        group = group.sort_values("week").copy()
        if len(group) < 52 or group["average_net_unit_price"].nunique() < 8:
            continue
        group["trend"] = np.arange(len(group), dtype=float)
        month_dummies = pd.get_dummies(group["week"].dt.month, prefix="month", drop_first=True)
        design = pd.concat(
            [
                np.log(group[["average_net_unit_price"]]).rename(
                    columns={"average_net_unit_price": "log_price"}
                ),
                group[["trend"]],
                month_dummies,
            ],
            axis=1,
        ).astype(float)
        target = np.log1p(group["orders"])
        model = LinearRegression().fit(design, target)
        rows.append(
            {
                "category_name": category,
                "weeks": len(group),
                "total_orders": int(group["orders"].sum()),
                "indicative_price_elasticity": float(model.coef_[0]),
                "r_squared": float(model.score(design, target)),
            }
        )
    return pd.DataFrame(rows).sort_values("total_orders", ascending=False)


def run_pricing_analysis() -> None:
    EXPORT_DIR.mkdir(parents=True, exist_ok=True)
    with sqlite3.connect(DATABASE_PATH) as connection:
        connection.executescript(
            (SQL_DIR / "04_pricing_analysis.sql").read_text(encoding="utf-8")
        )
        margin = pd.read_sql_query(
            "SELECT * FROM margin_by_dimension ORDER BY dimension, net_sales DESC",
            connection,
        )
        discount = pd.read_sql_query(
            "SELECT * FROM discount_summary ORDER BY discount_rate", connection
        )
        category_discount = pd.read_sql_query(
            "SELECT * FROM category_discount_summary ORDER BY category_name, discount_rate",
            connection,
        )
        items = pd.read_sql_query(
            """
            SELECT order_item_id, order_id, order_date, category_name, quantity,
                   gross_sales, discount_amount, discount_rate, net_sales, profit
            FROM analysis_order_items
            """,
            connection,
        )

    margin.to_csv(EXPORT_DIR / "margin_by_dimension.csv", index=False)
    discount.to_csv(EXPORT_DIR / "discount_summary.csv", index=False)
    category_discount.to_csv(EXPORT_DIR / "category_discount_summary.csv", index=False)

    cost = items["net_sales"] - items["profit"]
    scenarios = []
    for cap in CAPS:
        simulated_discount = np.minimum(items["discount_rate"], cap) * items["gross_sales"]
        simulated_net_sales = items["gross_sales"] - simulated_discount
        simulated_profit = simulated_net_sales - cost
        scenarios.append(
            {
                "discount_cap": cap,
                "affected_items": int((items["discount_rate"] > cap).sum()),
                "actual_profit": float(items["profit"].sum()),
                "simulated_profit_fixed_volume": float(simulated_profit.sum()),
                "accounting_profit_change": float(simulated_profit.sum() - items["profit"].sum()),
            }
        )
    cap_results = pd.DataFrame(scenarios)
    cap_results.to_csv(EXPORT_DIR / "discount_cap_scenarios.csv", index=False)

    sensitivity = _price_sensitivity(items)
    sensitivity.to_csv(EXPORT_DIR / "indicative_price_sensitivity.csv", index=False)

    overall_margin = items["profit"].sum() / items["net_sales"].sum()
    negative_rate = (items["profit"] < 0).mean()
    negative_discount_bands = discount.loc[discount["weighted_margin"] < 0]
    report = [
        "# Pricing and margin analysis",
        "",
        "Generated by `python -m src.pricing_analysis` from eligible order-item rows.",
        "",
        "## Portfolio-level findings",
        "",
        f"- Net sales: ${items['net_sales'].sum():,.2f}",
        f"- Profit: ${items['profit'].sum():,.2f}",
        f"- Weighted profit margin: {overall_margin:.2%}",
        f"- Negative-profit item rate: {negative_rate:.2%}",
        f"- Overall discount bands with negative weighted margin: {len(negative_discount_bands)}",
        "",
        "No aggregate margin breakpoint is asserted when no observed discount band has a negative weighted margin.",
        "",
        "## Discount-cap scenarios",
        "",
        "These scenarios hold quantity and inferred item cost constant. They are accounting sensitivities, not causal forecasts; they do not model lost demand from higher effective prices.",
        "",
        "| Cap | Affected items | Simulated profit | Accounting change |",
        "|---:|---:|---:|---:|",
    ]
    for row in cap_results.itertuples(index=False):
        report.append(
            f"| {row.discount_cap:.0%} | {row.affected_items:,} | "
            f"${row.simulated_profit_fixed_volume:,.2f} | ${row.accounting_profit_change:,.2f} |"
        )
    report.extend(
        [
            "",
            "## Price sensitivity",
            "",
            "The exported category estimates use weekly distinct orders, average realized net unit price, a time trend, and month controls. They are labeled indicative because price and product mix were not randomized and competitor prices are unavailable.",
            "",
        ]
    )
    (DOCS_DIR / "pricing_analysis.md").write_text("\n".join(report), encoding="utf-8")
    print("Pricing analysis exports and documentation created.")


if __name__ == "__main__":
    run_pricing_analysis()
